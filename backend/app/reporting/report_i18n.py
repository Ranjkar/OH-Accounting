"""Label translations for PDF/XLSX report content -- separate from the
frontend's next-intl dictionaries (different runtime, different
content: this is report/document copy, not UI chrome) and from
app/core/messages_i18n.py (ad-hoc backend-generated API strings, not
documents). Covers every report generator in app/reporting/ that
produces a human-facing document: vat (VAT return), financialOverview,
annualStatement, payslip, pnl (Profit & Loss), balanceSheet,
budgetVsActual.

Never translated anywhere in here: account/box codes ("1a", "5g", ...),
VAT percentages, enum values (e.g. `status.value`), company/customer
names, VAT/KVK numbers, amounts, EBITDA/EBIT (standard finance
acronyms with no established translated abbreviation in any of these
four languages, same choice as the frontend's dictionaries) -- only the
surrounding report prose and column/row labels.

`t()` falls back to Dutch for an unknown locale OR an unknown key
within a known locale (the same "never show nothing" principle as the
frontend's next-intl getMessageFallback), so a caller that adds a new
key to only one language can't produce a blank/crashing PDF -- it will
visibly fall back to Dutch for that one string until translated, not
silently resolve to an exception."""

