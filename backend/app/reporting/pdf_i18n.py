def t(locale: str, key: str, **params) -> str:
    strings = VAT_REPORT.get(locale, VAT_REPORT[DEFAULT_LOCALE])
    template = strings.get(key, VAT_REPORT[DEFAULT_LOCALE][key])
    return template.format(**params) if params else template


def box_description(locale: str, code: str) -> str:
    strings = VAT_REPORT.get(locale, VAT_REPORT[DEFAULT_LOCALE])
    return strings["box_descriptions"].get(code, VAT_REPORT[DEFAULT_LOCALE]["box_descriptions"][code])
